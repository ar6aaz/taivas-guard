FIELDS = (
    "rank", "domain", "issue_no", "rule_id", "family_id", "severity", "title",
    "adm", "network", "notice_ids", "comment_deadline", "source_url", "source_sha256",
)

TERRESTRIAL_FIELDS = (
    *FIELDS[:7], "assessment", "method", "frequency_mhz", "value_db", "limit_db", "margin_db", "mask_id",
    "worst_lat", "worst_lon", "worst_distance_km", "change", "fin_in_fxm_coord", "not_calculated_reason",
    "data_quality_items", *FIELDS[7:],
)
TERRESTRIAL_MASK_FILES = ("field_strength.json", "finland_boundary.json", "land_near_finland.json")


def _file_hash(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def _code_version() -> dict:
    try:
        def git(*args):
            return subprocess.check_output(
                ["git", *args], cwd=Path(__file__).resolve().parents[1], text=True,
                stderr=subprocess.DEVNULL,
            ).strip()
        return {"commit": git("rev-parse", "HEAD"), "dirty": bool(git("status", "--porcelain"))}
    except (OSError, subprocess.CalledProcessError):
        return {"commit": None, "dirty": None}

_TERRESTRIAL_LIMITATIONS = [
    "Possible concerns for expert review, not confirmed interference or regulatory breaches.",
    "T/R 25-08 Annex 1 values are indicative coordination thresholds. The document does not say whether they apply on the Russian border, and no bilateral agreement was checked.",
    "No value above 470 MHz is in the repository, so those notices report a field strength without a comparison.",
    "No terrain. Land/sea paths come from Natural Earth 1:50m, with lakes as land. Antenna patterns are not used.",
    "The 300 km screen and its polyline are engineering approximations, not regulatory values or a legal border.",
    "fxm_coord, action, target, pwr_eiv and pwr_xyz meanings are inferred from data, as the ITU ReadMe could not be read.",
    "Article 11 totals do not fully reconcile with notice rows; see funnel.json.",
    "No comment deadline is given: none for terrestrial notices is in the repository.",
    "Mobile stations without a notified antenna height are not calculated; see funnel.json.",
]


def _terrestrial_columns(record: dict) -> dict:
    details = record["details"]
    point = details.get("worst_point") or {}
    return {
        "assessment": details.get("assessment"),
        "method": details.get("method"),
        "frequency_mhz": details["source"]["rows"]["fxm_terra"].get("freq_assgn"),
        "value_db": details.get("value_db"),
        "limit_db": details.get("limit_db"),
        "margin_db": details.get("margin_db"),
        "mask_id": details.get("mask_id"),
        "worst_lat": point.get("lat"),
        "worst_lon": point.get("lon"),
        "worst_distance_km": point.get("distance_km"),
        "change": details["change"]["kind"],
        "fin_in_fxm_coord": details["fxm_coord"]["fin_named"],
        "not_calculated_reason": details.get("not_calculated_reason"),
        "data_quality_items": len(details.get("data_quality", [])),
    }


def export_issue(domain: str, issue_no: int, out: Path, *, sha256: str | None = None) -> dict:
    """Evaluate the latest imported revision (or an explicit hash) without changing reviews.

    Re-evaluation is intentional: Case is a mutable cross-issue review record, not
    a historical snapshot. No mail or events are generated by this operation.
    """
    settings = get_settings()
    with session_scope() as session:
        query = select(Artifact).where(Artifact.domain == domain, Artifact.issue_no == issue_no)
        if sha256:
            query = query.where(Artifact.sha256 == sha256)
        artifact = session.scalars(query.order_by(Artifact.id.desc())).first()
        if artifact is None:
            raise ValueError(f"No imported {domain} issue {issue_no} matching the requested revision.")

    started = perf_counter()
    reader = MdbReader(artifact.mdb_path)
    terrestrial = domain == TERRESTRIAL
    funnel = None
    if terrestrial:
        from .terrestrial.adapter import TerrestrialIssue
        from .terrestrial.rule_field_strength import terrestrial_rules

        issue = TerrestrialIssue(reader, expected_issue=issue_no)
        rules = terrestrial_rules(settings, issue_no, artifact.sha256)
    else:
        issue = SpaceIssue(reader)
        rules = space_rules(settings)
    hits = [hit for rule in rules for hit in rule.run(issue)]
    if terrestrial:
        funnel = rules[0].funnel
    hits.sort(key=lambda h: (
        {"high": 0, "medium": 1, "low": 2}[h.severity],
        h.comment_deadline.isoformat() if h.comment_deadline else "9999-12-31",
        -h.details.get("severity_score", 0), -h.details.get("margin_db", 0),
        h.rule_id, h.family_id,
    ))
    records = []
    for rank, hit in enumerate(hits, 1):
        record = asdict(hit)
        record.update(rank=rank, domain=domain, issue_no=issue_no,
                      source_url=artifact.source_url, source_sha256=artifact.sha256)
        record["notice_ids"] = [str(n) for n in sorted(hit.notice_ids)]
        record["comment_deadline"] = hit.comment_deadline.isoformat() if hit.comment_deadline else None
        record["details"].setdefault("method", "screening")
        if not terrestrial:  # Terrestrial databases have no readable version table.
            record["details"]["database_version"] = issue.database_version
        record["details"]["source"] = {
            **record["details"].get("source", {}),
            "domain": domain, "issue_no": issue_no,
            "notice_ids": record["notice_ids"], "sha256": artifact.sha256,
        }
        records.append(record)

    # Explicit whitelist: credentials and mail recipients never belong in exports.
    config_names = ("neighbour_adms", "terrestrial_distance_limits_km") if terrestrial else (
        "gso_visible_west_deg", "gso_visible_east_deg", "ngso_min_inclination_deg", "comment_window_months",
    )
    config = {name: getattr(settings, name) for name in config_names}
    config["m4_filter_sha256"] = _file_hash(settings.m4_filter_path)
    if terrestrial:
        from .terrestrial.rule_field_strength import MASK_DIR

        config["data_sha256"] = {name: _file_hash(MASK_DIR / name) for name in TERRESTRIAL_MASK_FILES}
    manifest = {
        "format_version": 1, "provisional_format": True,
        "domain": domain, "issue_no": issue_no, "source_url": artifact.source_url,
        "source_sha256": artifact.sha256,
        "mdb_sha256": _file_hash(Path(artifact.mdb_path)),
        "source_size_bytes": artifact.size_bytes, "code_version": _code_version(),
        "code_sha256": {
            str(path.relative_to(Path(__file__).parent)).replace("\\", "/"): _file_hash(path)
            for path in sorted(Path(__file__).parent.rglob("*.py"))
        },
        "config": config,
        "rule_ids": [r for rule in rules for r in getattr(rule, "emits", (rule.id,))],
        "case_count": len(records),
        "scope": {"service": "land mobile, station classes FB and ML", "funnel_file": "funnel.json"} if terrestrial else {
            "notice_reasons": sorted(IN_SCOPE_REASONS), "ap30_coverage": "not implemented",
        },
        "limitations": _TERRESTRIAL_LIMITATIONS if terrestrial else [
            "Possible concerns for expert review, not confirmed interference or regulatory breaches.",
            "AP30/AP30A/AP30B are not screened; current scope is API/A and CR/C.",
            "No beam coverage: pfd calculations apply maximum notified gain towards Finland, and non-GSO results may be upper bounds.",
            "Special-interest station overlap is frequency overlap only, on RX and TX bands; stations with neither frequency are skipped.",
            "Comment deadlines are estimates requiring expert confirmation.",
        ],
        "generated_at": datetime.now(UTC).isoformat(),
        "run_time_s": round(perf_counter() - started, 6),
    }
    out.mkdir(parents=True, exist_ok=True)
    (out / "cases.json").write_text(json.dumps(records, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    outputs = ["cases.csv", "cases.json"]
    if terrestrial:
        (out / "funnel.json").write_text(json.dumps(funnel, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
        outputs.append("funnel.json")
    with (out / "cases.csv").open("w", newline="", encoding="utf-8") as stream:
        # Fixed line endings: the hashes below must verify on any platform and after a git checkout.
        writer = csv.DictWriter(stream, fieldnames=TERRESTRIAL_FIELDS if terrestrial else FIELDS, extrasaction="ignore", lineterminator="\n")
        writer.writeheader()
        for record in records:
            row = {**record, "notice_ids": ";".join(record["notice_ids"])}
            writer.writerow({**row, **_terrestrial_columns(record)} if terrestrial else row)
    manifest["output_sha256"] = {
        name: hashlib.sha256((out / name).read_bytes()).hexdigest()
        for name in outputs
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    return manifest
